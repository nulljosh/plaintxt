#!/usr/bin/env python3
"""Writes landing/ide-files.js: the real files the landing's IDE demo opens, their real counts, and what the
checks print when they pass. Run it after changing Stats.swift, Checks/main.swift or README.md."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
files = ["ios/App/Stats.swift", "ios/Checks/main.swift", "README.md"]

out = []
for f in files:
    t = (root / f).read_text()
    out.append({"path": f, "text": t})  # counted in the page by the same rules as Stats.swift
checks = (root / "ios/Checks/main.swift").read_text()
build = [json.loads('"' + s + '"').replace("\u2705 ", "") for s in re.findall(r'^print\("((?:[^"\\]|\\.)*)"\)', checks, re.M)]
(root / "landing/ide-files.js").write_text("// Generated by tools/ide-demo.py from the repo. Do not edit.\nwindow.IDE_FILES = "
                                            + json.dumps({"files": out, "build": build}, ensure_ascii=False) + ";\n")
print(len(out), "files,", len(build), "build lines")
